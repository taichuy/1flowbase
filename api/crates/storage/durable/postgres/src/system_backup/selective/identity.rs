//! Transaction-local identity handling; archive columns and exact row upserts stay unchanged.
use super::{archive::Table, schema};
use anyhow::Result;
use sqlx::{PgConnection, Row};

pub(super) struct IdentityColumn {
    table: String,
    column: String,
    sequence: String,
    always: bool,
    increment: i64,
    minimum: i64,
    maximum: i64,
    cache: i64,
}

pub(super) async fn prepare(
    connection: &mut PgConnection,
    tables: &[Table],
) -> Result<Vec<IdentityColumn>> {
    let names: Vec<_> = tables.iter().map(|table| table.name.as_str()).collect();
    let rows = sqlx::query("select n.nspname, c.relname, a.attname, a.attidentity='a' as always, sn.nspname as sequence_schema, sc.relname as sequence_name, s.seqincrement, s.seqmin, s.seqmax, s.seqcache from pg_attribute a join pg_class c on c.oid=a.attrelid join pg_namespace n on n.oid=c.relnamespace join pg_class sc on sc.oid=pg_get_serial_sequence(format('%I.%I',n.nspname,c.relname),a.attname)::regclass join pg_namespace sn on sn.oid=sc.relnamespace join pg_sequence s on s.seqrelid=sc.oid where n.nspname=current_schema() and c.relname=any($1) and a.attidentity<>'' and not a.attisdropped order by c.relname,a.attnum")
        .bind(&names).fetch_all(&mut *connection).await?;
    let mut columns = Vec::new();
    for row in rows {
        let column = IdentityColumn {
            table: format!(
                "{}.{}",
                schema::quote(row.try_get("nspname")?)?,
                schema::quote(row.try_get("relname")?)?
            ),
            column: schema::quote(row.try_get("attname")?)?,
            sequence: format!(
                "{}.{}",
                schema::quote(row.try_get("sequence_schema")?)?,
                schema::quote(row.try_get("sequence_name")?)?
            ),
            always: row.try_get("always")?,
            increment: row.try_get("seqincrement")?,
            minimum: row.try_get("seqmin")?,
            maximum: row.try_get("seqmax")?,
            cache: row.try_get("seqcache")?,
        };
        // Lock table writers and sequence allocators until Prepared commits or rolls back.
        // SQL safety: every identifier comes from the live catalog and passes schema::quote.
        let lock = format!("lock table {} in access exclusive mode", column.table);
        sqlx::query(sqlx::AssertSqlSafe(lock.as_str()))
            .execute(&mut *connection)
            .await?;
        if column.always {
            let sql = format!(
                "alter table {} alter column {} set generated by default",
                column.table, column.column
            );
            sqlx::query(sqlx::AssertSqlSafe(sql.as_str()))
                .execute(&mut *connection)
                .await?;
        }
        // CACHE 1 prevents the boundary-marking nextval in finish from reserving a new batch.
        // ALTER SEQUENCE also excludes direct nextval/setval calls before reading its state.
        let sql = format!("alter sequence {} cache 1", column.sequence);
        sqlx::query(sqlx::AssertSqlSafe(sql.as_str()))
            .execute(&mut *connection)
            .await?;
        columns.push(column);
    }
    Ok(columns)
}

pub(super) async fn finish(
    connection: &mut PgConnection,
    columns: Vec<IdentityColumn>,
) -> Result<()> {
    for column in columns {
        let sql = format!("select last_value,is_called from {}", column.sequence);
        let state = sqlx::query(sqlx::AssertSqlSafe(sql.as_str()))
            .fetch_one(&mut *connection)
            .await?;
        let last: i64 = state.try_get("last_value")?;
        let was_called: bool = state.try_get("is_called")?;
        let positive = column.increment > 0;
        let aggregate = if positive { "max" } else { "min" };
        let sql = format!(
            "select {aggregate}({})::bigint from {}",
            column.column, column.table
        );
        let extreme: Option<i64> = sqlx::query_scalar(sqlx::AssertSqlSafe(sql.as_str()))
            .fetch_one(&mut *connection)
            .await?;
        let occupied = extreme.is_some_and(|value| {
            if positive {
                value >= last
            } else {
                value <= last
            }
        });
        let boundary = extreme
            .map_or(last, |value| {
                if positive {
                    last.max(value)
                } else {
                    last.min(value)
                }
            })
            .clamp(column.minimum, column.maximum);
        // RESTART rewrites sequence storage transactionally and invalidates backend caches.
        // Clamping retains PostgreSQL's native exhaustion/cycle behavior at the sequence bounds.
        let sql = format!("alter sequence {} restart with {boundary}", column.sequence);
        sqlx::query(sqlx::AssertSqlSafe(sql.as_str()))
            .execute(&mut *connection)
            .await?;
        if was_called || occupied {
            sqlx::query_scalar::<_, i64>("select nextval($1::regclass)")
                .bind(&column.sequence)
                .fetch_one(&mut *connection)
                .await?;
        }
        let sql = format!("alter sequence {} cache {}", column.sequence, column.cache);
        sqlx::query(sqlx::AssertSqlSafe(sql.as_str()))
            .execute(&mut *connection)
            .await?;
        if column.always {
            let sql = format!(
                "alter table {} alter column {} set generated always",
                column.table, column.column
            );
            sqlx::query(sqlx::AssertSqlSafe(sql.as_str()))
                .execute(&mut *connection)
                .await?;
        }
    }
    Ok(())
}
