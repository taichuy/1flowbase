import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const themeCss = await readFile(
  resolve(packageRoot, '../../node_modules/tailwindcss/theme.css'),
  'utf8'
);
const preflightCss = await readFile(
  resolve(packageRoot, '../../node_modules/tailwindcss/preflight.css'),
  'utf8'
);
const utilitiesCss = await readFile(
  resolve(packageRoot, '../../node_modules/tailwindcss/utilities.css'),
  'utf8'
);
const source = `// Generated by scripts/generate-stylesheet-contract.mjs from tailwindcss@4.3.3.\nexport const TAILWIND_THEME_CSS = ${JSON.stringify(themeCss)};\nexport const TAILWIND_PREFLIGHT_CSS = ${JSON.stringify(preflightCss)};\nexport const TAILWIND_UTILITIES_CSS = ${JSON.stringify(utilitiesCss)};\nexport const TAILWIND_STYLESHEET_SHA256 = '${createHash('sha256').update(`${themeCss}\n${preflightCss}\n${utilitiesCss}`).digest('hex')}';\n`;
const target = resolve(packageRoot, 'src/stylesheet-contract.ts');
await mkdir(dirname(target), { recursive: true });
await writeFile(target, source, 'utf8');
