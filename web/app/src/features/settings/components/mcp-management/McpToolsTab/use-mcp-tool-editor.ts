import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { Form, Modal, App } from 'antd';
import {
  useCallback,
  useEffect,
  useReducer,
  useRef,
  useState,
  type SetStateAction
} from 'react';
import type {
  ConsoleMcpInterfaceCapability,
  ConsoleMcpProxyInputMapping,
  ConsoleMcpProxyOutputMapping,
  ConsoleMcpTool,
  SaveConsoleMcpToolBody
} from '@1flowbase/api-client';

import {
  createSettingsMcpTool,
  fetchSettingsMcpInterfaceCapability,
  fetchSettingsMcpTool,
  invalidateSettingsMcpInstancesAndTools,
  settingsMcpInterfaceCapabilityDetailQueryKey,
  settingsMcpToolDetailQueryKey,
  updateSettingsMcpTool
} from '../../../api/mcp-management';
import { useAuthStore } from '../../../../../state/auth-store';

import { i18nText } from '../../../../../shared/i18n/text';

import {
  buildInputMappingFromInterface,
  inputMappingHasContent,
  MCP_CALL_PARAMETERS,
  normalizeInputMapping,
  withLegacyCallMappings
} from '../mcp-input-mapping-model';

import { mcpProxyMappingIsValid } from '../proxy/mcp-proxy-mapping-model';

import { initialMcpToolsState, mcpToolsReducer } from '../mcp-management-state';
import { buildRandomToolIdSeed } from '../mcp-management-view-model';

import {
  TOOL_FORM_STEPS,
  emptyObjectSchema,
  schemaMappingHasContent,
  schemaRecord,
  parseResponseFields,
  toUpdateToolBody,
  type ToolFormValues
} from './tool-editor-model';

/** Owns the tool form, on-demand tool/interface detail loading, schema validity and save transaction. */
export function useMcpToolEditor() {
  const { message } = App.useApp();
  const csrfToken = useAuthStore((state) => state.csrfToken ?? '');
  const queryClient = useQueryClient();
  const [form] = Form.useForm<ToolFormValues>();
  const [toolsState, dispatchToolsState] = useReducer(
    mcpToolsReducer,
    initialMcpToolsState
  );
  const { modalOpen, editingTool, step, exportingCatalog } = toolsState;
  const [editingToolId, setEditingToolId] = useState<string | null>(null);
  const [selectedInterfaceId, setSelectedInterfaceId] = useState<
    string | undefined
  >(undefined);
  const [toolDetailError, setToolDetailError] = useState(false);
  const setModalOpen = useCallback(
    (value: SetStateAction<boolean>) =>
      dispatchToolsState({ type: 'setModalOpen', value }),
    []
  );
  const setEditingTool = useCallback(
    (value: SetStateAction<ConsoleMcpTool | null>) =>
      dispatchToolsState({ type: 'setEditingTool', value }),
    []
  );
  const setStep = useCallback(
    (value: SetStateAction<string>) =>
      dispatchToolsState({ type: 'setStep', value }),
    []
  );
  const setExportingCatalog = useCallback(
    (value: SetStateAction<boolean>) =>
      dispatchToolsState({ type: 'setExportingCatalog', value }),
    []
  );
  const autoGeneratedToolIdRef = useRef('');
  const inputMappingValidRef = useRef(true);
  const outputMappingValidRef = useRef(true);
  const parameterSchemaValidRef = useRef(true);
  const resultSchemaValidRef = useRef(true);
  const [schemaEditorRevision, bumpSchemaEditorRevision] = useReducer(
    (value: number) => value + 1,
    0
  );
  const [callParametersVisible, setCallParametersVisible] = useState(false);

  const interfaceDetailEnabled =
    modalOpen &&
    Boolean(selectedInterfaceId) &&
    (!editingTool || editingTool.execution_target.kind === 'interface_wrapper');
  const selectedInterfaceQuery = useQuery({
    queryKey: settingsMcpInterfaceCapabilityDetailQueryKey(
      selectedInterfaceId ?? ''
    ),
    queryFn: () => fetchSettingsMcpInterfaceCapability(selectedInterfaceId!),
    enabled: interfaceDetailEnabled
  });
  const selectedInterface =
    selectedInterfaceQuery.data?.interface_id === selectedInterfaceId
      ? selectedInterfaceQuery.data
      : undefined;

  const hydrateToolForm = useCallback(
    (record: ConsoleMcpTool) => {
      autoGeneratedToolIdRef.current = '';
      inputMappingValidRef.current = true;
      outputMappingValidRef.current = true;
      parameterSchemaValidRef.current = true;
      resultSchemaValidRef.current = true;
      setEditingTool(record);
      setSelectedInterfaceId(
        record.execution_target.kind === 'interface_wrapper'
          ? record.execution_target.interface_id
          : undefined
      );
      setCallParametersVisible(
        record.execution_target.kind === 'interface_wrapper'
      );
      form.setFieldsValue({
        tool_id: record.tool_id,
        name: record.name,
        short_description: record.short_description,
        full_description: record.full_description,
        max_inline_chars: record.max_inline_chars,
        response_fields:
          record.response_fields === null
            ? undefined
            : JSON.stringify(record.response_fields),
        des_id: record.des_id,
        execution_target_kind: record.execution_target.kind,
        interface_id:
          record.execution_target.kind === 'interface_wrapper'
            ? record.execution_target.interface_id
            : undefined,
        upstream_connection_id:
          record.execution_target.kind === 'mcp_proxy'
            ? record.execution_target.upstream_connection_id
            : undefined,
        remote_tool_name:
          record.execution_target.kind === 'mcp_proxy'
            ? record.execution_target.remote_tool_name
            : undefined,
        source_schema_hash:
          record.execution_target.kind === 'mcp_proxy'
            ? record.execution_target.source_schema_hash
            : undefined,
        capability_code:
          record.execution_target.kind === 'assistant_client'
            ? record.execution_target.capability_code
            : undefined,
        risk_level: record.risk_level,
        status: record.status
      });
      form.setFieldValue(
        'parameter_schema',
        schemaRecord(record.parameter_schema)
      );
      form.setFieldValue('result_schema', schemaRecord(record.result_schema));
      form.setFieldValue(
        'input_mapping',
        record.execution_target.kind === 'mcp_proxy'
          ? record.input_mapping
          : record.execution_target.kind === 'interface_wrapper'
            ? withLegacyCallMappings(record.input_mapping)
            : normalizeInputMapping(record.input_mapping)
      );
      form.setFieldValue(
        'output_mapping',
        record.execution_target.kind === 'mcp_proxy'
          ? record.output_mapping
          : schemaRecord(record.output_mapping)
      );
      bumpSchemaEditorRevision();
    },
    [form, setEditingTool]
  );

  // The request result, not the observer's cached value, starts an edit session.
  // Closing or switching tools retires this request; later cache writes aren't form edits.
  useEffect(() => {
    if (!editingToolId) return;
    const queryKey = settingsMcpToolDetailQueryKey(editingToolId);
    let current = true;
    void queryClient
      .fetchQuery({ queryKey, queryFn: () => fetchSettingsMcpTool(editingToolId), staleTime: 0 })
      .then((detail) => {
        if (!current) return;
        if (detail.tool_id === editingToolId) hydrateToolForm(detail);
        else setToolDetailError(true);
      }, () => {
        if (current) setToolDetailError(true);
      });
    return () => {
      current = false;
      // A same-ID reopen must not join an unfinished read from the closed session.
      void queryClient.cancelQueries({ queryKey, exact: true });
    };
  }, [editingToolId, hydrateToolForm, queryClient]);

  const openEditTool = useCallback(
    (toolId: string) => {
      setToolDetailError(false);
      setEditingTool(null);
      setEditingToolId(toolId);
      setStep('basic');
      setModalOpen(true);
    },
    [setEditingTool, setModalOpen, setStep]
  );

  const openCreateTool = useCallback(() => {
    setToolDetailError(false);
    autoGeneratedToolIdRef.current = '';
    inputMappingValidRef.current = true;
    outputMappingValidRef.current = true;
    parameterSchemaValidRef.current = true;
    resultSchemaValidRef.current = true;
    setEditingToolId(null);
    setEditingTool(null);
    setSelectedInterfaceId(undefined);
    setCallParametersVisible(false);
    setStep('basic');
    form.setFieldsValue({
      tool_id: '',
      name: '',
      short_description: '',
      full_description: '',
      max_inline_chars: undefined,
      response_fields: undefined,
      des_id: buildRandomToolIdSeed(),
      execution_target_kind: 'interface_wrapper',
      interface_id: undefined,
      risk_level: 'high',
      status: 'draft'
    });
    form.setFieldValue('parameter_schema', emptyObjectSchema());
    form.setFieldValue('result_schema', emptyObjectSchema());
    form.setFieldValue('input_mapping', {
      interface_parameters: MCP_CALL_PARAMETERS,
      mappings: []
    });
    form.setFieldValue('output_mapping', emptyObjectSchema());
    bumpSchemaEditorRevision();
    setModalOpen(true);
  }, [form, setEditingTool, setModalOpen, setStep]);

  const closeToolModal = useCallback(() => {
    setModalOpen(false);
    setEditingToolId(null);
    setEditingTool(null);
    setSelectedInterfaceId(undefined);
  }, [setEditingTool, setModalOpen]);
  const setInputMappingValue = useCallback(
    (mapping: ToolFormValues['input_mapping']) =>
      form.setFieldValue('input_mapping', mapping),
    [form]
  );
  const setOutputMappingValue = useCallback(
    (schema: ToolFormValues['output_mapping']) =>
      form.setFieldValue('output_mapping', schema),
    [form]
  );
  const setParameterSchemaValue = useCallback(
    (schema: ToolFormValues['parameter_schema']) =>
      form.setFieldValue('parameter_schema', schema),
    [form]
  );
  const setResultSchemaValue = useCallback(
    (schema: ToolFormValues['result_schema']) =>
      form.setFieldValue('result_schema', schema),
    [form]
  );
  const setInputMappingValidity = useCallback((valid: boolean) => {
    inputMappingValidRef.current = valid;
  }, []);
  const setOutputMappingValidity = useCallback((valid: boolean) => {
    outputMappingValidRef.current = valid;
  }, []);
  const setParameterSchemaValidity = useCallback((valid: boolean) => {
    parameterSchemaValidRef.current = valid;
  }, []);
  const setResultSchemaValidity = useCallback((valid: boolean) => {
    resultSchemaValidRef.current = valid;
  }, []);
  const saveToolMutation = useMutation({
    mutationFn: async (values: ToolFormValues) => {
      if (!parameterSchemaValidRef.current) {
        throw new Error('parameter_schema JSON');
      }
      if (!resultSchemaValidRef.current) {
        throw new Error('result_schema JSON');
      }
      if (!inputMappingValidRef.current) {
        throw new Error(
          i18nText('settingsMcpManagement', 'mcp_mapping_default_invalid')
        );
      }
      if (!outputMappingValidRef.current) {
        throw new Error('output_mapping JSON');
      }
      const common = {
        tool_id: editingTool ? editingTool.tool_id : values.tool_id,
        des_id: values.des_id,
        name: values.name,
        short_description: values.short_description,
        full_description: values.full_description,
        max_inline_chars: form.getFieldValue('max_inline_chars') ?? null,
        response_fields: parseResponseFields(
          form.getFieldValue('response_fields')
        ),
        status: values.status
      };
      let body: SaveConsoleMcpToolBody;
      if (editingTool?.execution_target.kind === 'assistant_client') {
        body = {
          ...common,
          execution_target: editingTool.execution_target,
          parameter_schema: schemaRecord(
            form.getFieldValue('parameter_schema')
          ),
          result_schema: schemaRecord(form.getFieldValue('result_schema')),
          input_mapping: schemaRecord(form.getFieldValue('input_mapping')),
          output_mapping: schemaRecord(form.getFieldValue('output_mapping')),
          permission_code: editingTool.permission_code,
          risk_level: form.getFieldValue('risk_level') as string
        };
      } else if (editingTool?.execution_target.kind === 'mcp_proxy') {
        const inputMapping = form.getFieldValue(
          'input_mapping'
        ) as ConsoleMcpProxyInputMapping;
        const outputMapping = form.getFieldValue(
          'output_mapping'
        ) as ConsoleMcpProxyOutputMapping;
        if (
          !mcpProxyMappingIsValid(inputMapping) ||
          !mcpProxyMappingIsValid(outputMapping)
        ) {
          throw new Error(
            i18nText('settingsMcpManagement', 'auto.proxy_path_invalid')
          );
        }
        body = {
          ...common,
          execution_target: editingTool.execution_target,
          parameter_schema: schemaRecord(
            form.getFieldValue('parameter_schema')
          ),
          result_schema: schemaRecord(form.getFieldValue('result_schema')),
          input_mapping: inputMapping,
          output_mapping: outputMapping,
          permission_code: editingTool.permission_code,
          risk_level: form.getFieldValue('risk_level') as string
        };
      } else {
        if (!values.interface_id) {
          throw new Error('operation is required');
        }
        const resolvedInterface =
          selectedInterface?.interface_id === values.interface_id
            ? selectedInterface
            : await queryClient.fetchQuery({
                queryKey: settingsMcpInterfaceCapabilityDetailQueryKey(
                  values.interface_id
                ),
                queryFn: () =>
                  fetchSettingsMcpInterfaceCapability(values.interface_id!)
              });
        if (!resolvedInterface) {
          throw new Error('operation is required');
        }
        body = {
          ...common,
          execution_target: {
            kind: 'interface_wrapper',
            interface_id: values.interface_id
          },
          parameter_schema: resolvedInterface.parameter_schema,
          result_schema: resolvedInterface.result_schema,
          input_mapping: normalizeInputMapping(
            form.getFieldValue('input_mapping')
          ),
          output_mapping: schemaRecord(form.getFieldValue('output_mapping')),
          permission_code: resolvedInterface.permission_code,
          risk_level: resolvedInterface.risk_level
        };
      }
      if (editingTool) {
        return updateSettingsMcpTool(
          editingTool.tool_id,
          toUpdateToolBody(body),
          csrfToken
        );
      }
      return createSettingsMcpTool(body, csrfToken);
    },
    onSuccess: async () => {
      message.success(i18nText('settings', 'auto.mcp_saved'));
      closeToolModal();
      await invalidateSettingsMcpInstancesAndTools(queryClient);
    },
    onError: (error) => {
      message.error(error instanceof Error ? error.message : String(error));
    }
  });
  async function applyInterfaceToMapping(
    field: 'input_mapping' | 'output_mapping',
    entry?: ConsoleMcpInterfaceCapability
  ) {
    const interfaceId =
      selectedInterfaceId ??
      (form.getFieldValue('interface_id') as string | undefined);
    let resolvedEntry =
      entry?.interface_id === interfaceId
        ? entry
        : selectedInterface?.interface_id === interfaceId
          ? selectedInterface
          : undefined;
    if (!resolvedEntry && interfaceId) {
      try {
        resolvedEntry = await queryClient.ensureQueryData({
          queryKey:
            settingsMcpInterfaceCapabilityDetailQueryKey(interfaceId),
          queryFn: () => fetchSettingsMcpInterfaceCapability(interfaceId)
        });
      } catch (error) {
        message.error(error instanceof Error ? error.message : String(error));
        return;
      }
    }
    if (!resolvedEntry) {
      return;
    }

    const nextMapping =
      field === 'input_mapping'
        ? buildInputMappingFromInterface(resolvedEntry, form.getFieldValue(field))
        : schemaRecord(resolvedEntry.result_schema);
    const currentHasContent =
      field === 'input_mapping'
        ? inputMappingHasContent(form.getFieldValue(field))
        : schemaMappingHasContent(form.getFieldValue(field));
    const applyMapping = () => {
      form.setFieldValue(field, nextMapping);
      if (field === 'input_mapping') {
        inputMappingValidRef.current = true;
        setCallParametersVisible(true);
      } else {
        outputMappingValidRef.current = true;
      }
      bumpSchemaEditorRevision();
    };

    if (!currentHasContent) {
      applyMapping();
      return;
    }

    Modal.confirm({
      title: i18nText('settings', 'auto.mcp_mapping_overwrite_confirm_title'),
      content: i18nText(
        'settings',
        'auto.mcp_mapping_overwrite_confirm_content'
      ),
      okText: i18nText('settings', 'auto.confirm'),
      cancelText: i18nText('settings', 'auto.cancel'),
      onOk: applyMapping
    });
  }
  const toolStepIndex = Math.max(
    0,
    TOOL_FORM_STEPS.findIndex((entry) => entry.value === step)
  );
  const previousToolStep = TOOL_FORM_STEPS[toolStepIndex - 1];
  const nextToolStep = TOOL_FORM_STEPS[toolStepIndex + 1];

  return {
    form,
    modalOpen,
    editingTool,
    editingToolId,
    toolDetailLoading: Boolean(editingToolId) && !editingTool,
    toolDetailError,
    selectedInterfaceId,
    setSelectedInterfaceId,
    selectedInterface,
    selectedInterfaceLoading: selectedInterfaceQuery.isLoading,
    step,
    exportingCatalog,
    openCreateTool,
    openEditTool,
    closeToolModal,
    setStep,
    setExportingCatalog,
    autoGeneratedToolIdRef,
    schemaEditorRevision,
    callParametersVisible,
    setInputMappingValue,
    setOutputMappingValue,
    setParameterSchemaValue,
    setResultSchemaValue,
    setInputMappingValidity,
    setOutputMappingValidity,
    setParameterSchemaValidity,
    setResultSchemaValidity,
    saveToolMutation,
    applyInterfaceToMapping,
    toolStepIndex,
    previousToolStep,
    nextToolStep
  };
}
