import { useQueryClient } from '@tanstack/react-query';
import { useAuthStore } from '../../../../state/auth-store';
import { useMcpToolEditor } from './McpToolsTab/use-mcp-tool-editor';
import { useMcpToolsCatalog } from './McpToolsTab/use-mcp-tools-catalog';
import DeleteOutlined from '@ant-design/icons/es/icons/DeleteOutlined';
import UploadOutlined from '@ant-design/icons/es/icons/UploadOutlined';
import EditOutlined from '@ant-design/icons/es/icons/EditOutlined';
import LeftOutlined from '@ant-design/icons/es/icons/LeftOutlined';
import PlusOutlined from '@ant-design/icons/es/icons/PlusOutlined';
import ReloadOutlined from '@ant-design/icons/es/icons/ReloadOutlined';
import RightOutlined from '@ant-design/icons/es/icons/RightOutlined';

import {
  Button,
  Descriptions,
  Flex,
  Form,
  Input,
  Popconfirm,
  Select,
  Segmented,
  Space,
  Steps,
  Tag,
  Tooltip,
  Typography
} from 'antd';
import { useMemo } from 'react';
import type {
  ConsoleMcpCatalog,
  ConsoleMcpInterfaceCapability,
  ConsoleMcpProxyInputMapping,
  ConsoleMcpProxyOutputMapping,
  ConsoleMcpTool
} from '@1flowbase/api-client';

import {
  executeSettingsMcpToolDebug,
  executeSettingsMcpProxyToolDebug,
  settingsMcpCatalogQueryKey
} from '../../api/mcp-management';

import {
  DataTable,
  DataTableColumnSettings,
  type DataTableColumn
} from '../../../../shared/ui/data-table/DataTable';
import { useUserPreferenceDataTableConfiguration } from '../../../../shared/ui/data-table/user-preference-data-table';
import {
  DataTableFilterField,
  DataTableFilterForm,
  DataTableLayout
} from '../../../../shared/ui/data-table/DataTableLayout';
import { i18nText } from '../../../../shared/i18n/text';
import { FixedHeightModal } from '../../../../shared/ui/fixed-height-modal/FixedHeightModal';
import { MarkdownIrEditor } from '../../../../shared/ui/markdown-ir-editor/MarkdownIrEditor';
import { JsonSchemaInlineEditor } from '../../../agent-flow/components/detail/fields/json-schema/JsonSchemaSettingsPanel';
import {
  buildRandomToolIdSeed,
  buildReadableToolId
} from './mcp-management-view-model';
import {
  MCP_CALL_PARAMETERS,
  normalizeInputMapping,
  withLegacyCallMappings
} from './mcp-input-mapping-model';
import { McpInputMappingEditor } from './McpInputMappingEditor';
import { McpToolDebugPanel } from './McpToolDebugPanel';
import { McpProxyMappingEditor } from './proxy/McpProxyMappingEditor';

import { McpProxyToolDebugPanel } from './proxy/McpProxyToolDebugPanel';

import { riskColor, statusColor } from './mcp-management-utils';
import {
  TOOL_FORM_STEPS,
  emptyObjectSchema,
  interfaceOptionLabel,
  schemaRecord,
  toolSourceLabel,
  toolTypeLabel
} from './McpToolsTab/tool-editor-model';
import { SelectedInterfaceOperationTitle } from './McpToolsTab/SelectedInterfaceOperationTitle';
import { McpToolReturnDefaultsFields } from './McpToolsTab/McpToolReturnDefaultsFields';
import {
  MCP_TOOLS_PAGE_SIZE,
  type McpToolsRouteState
} from './McpToolsTab/route-state';

export function McpToolsTab({
  canManage,
  catalog,
  interfaceCapabilities
}: {
  canManage: boolean;
  catalog: ConsoleMcpCatalog;
  interfaceCapabilities: ConsoleMcpInterfaceCapability[];
}) {
  const csrfToken = useAuthStore((state) => state.csrfToken ?? '');
  const queryClient = useQueryClient();
  const editor = useMcpToolEditor(interfaceCapabilities);
  const {
    form,
    modalOpen,
    editingTool,
    step,
    exportingCatalog,
    setModalOpen,
    setEditingTool,
    setStep,
    autoGeneratedToolIdRef,
    inputMappingValidRef,
    outputMappingValidRef,
    parameterSchemaValidRef,
    resultSchemaValidRef,
    schemaEditorRevision,
    bumpSchemaEditorRevision,
    callParametersVisible,
    setCallParametersVisible,
    setInputMappingValue,
    setOutputMappingValue,
    setParameterSchemaValue,
    setResultSchemaValue,
    setInputMappingValidity,
    setOutputMappingValidity,
    setParameterSchemaValidity,
    setResultSchemaValidity,
    saveToolMutation,
    applyInterfaceToMapping,
    toolStepIndex,
    previousToolStep,
    nextToolStep
  } = editor;
  const {
    routeState,
    filterDraft,
    setFilterDraft,
    updateRouteState,
    refreshMutation,
    deleteToolMutationRef,
    refreshMutationRef,
    handleExportCatalog,
    filteredTools,
    visibleTools,
    applyFilters,
    resetFilters
  } = useMcpToolsCatalog(catalog, editor);

  const columns = useMemo<Array<DataTableColumn<ConsoleMcpTool>>>(
    () => [
      {
        key: 'name',
        title: i18nText('settings', 'auto.tool_name'),
        dataIndex: 'name',
        width: 220,
        ellipsis: true
      },
      {
        key: 'tool_id',
        title: 'tool_id',
        dataIndex: 'tool_id',
        width: 180,
        ellipsis: true
      },
      {
        key: 'operation',
        title: 'operation',
        dataIndex: 'operation',
        width: 240,
        ellipsis: true,
        render: (_, record) =>
          record.operation?.trim() ? record.operation : toolSourceLabel(record)
      },
      {
        key: 'execution_target_kind',
        title: i18nText('settingsMcpManagement', 'auto.tool_type'),
        width: 130,
        render: (_, record) => <Tag>{toolTypeLabel(record)}</Tag>
      },
      {
        key: 'execution_source',
        title: i18nText('settingsMcpManagement', 'auto.execution_source'),
        width: 260,
        ellipsis: true,
        render: (_, record) => toolSourceLabel(record)
      },
      {
        key: 'risk_level',
        title: 'risk_level',
        dataIndex: 'risk_level',
        width: 120,
        render: (value) => (
          <Tag color={riskColor(String(value))}>{String(value)}</Tag>
        )
      },
      {
        key: 'managed_by',
        title: i18nText('settingsMcpManagement', 'auto.bundle_source'),
        width: 240,
        render: (_, record) =>
          record.managed_by ? (
            <Tag color="blue">
              {record.managed_by.organization}/{record.managed_by.bundle_id}@
              {record.managed_by.bundle_version}
            </Tag>
          ) : (
            '-'
          )
      },
      {
        key: 'des_id',
        title: 'des_id',
        dataIndex: 'des_id',
        width: 140
      },
      {
        key: 'status',
        title: 'status',
        dataIndex: 'status',
        width: 120,
        render: (value) => (
          <Tag color={statusColor(String(value))}>{String(value)}</Tag>
        )
      }
    ],
    []
  );
  const tableColumns = useMemo<Array<DataTableColumn<ConsoleMcpTool>>>(
    () => [
      ...columns,
      {
        key: 'actions',
        title: i18nText('settings', 'auto.operation'),
        width: 180,
        render: (_, record) => (
          <Space>
            <Button
              icon={<EditOutlined />}
              size="small"
              disabled={!canManage}
              onClick={() => {
                autoGeneratedToolIdRef.current = '';
                inputMappingValidRef.current = true;
                outputMappingValidRef.current = true;
                parameterSchemaValidRef.current = true;
                resultSchemaValidRef.current = true;
                setEditingTool(record);
                setCallParametersVisible(
                  record.execution_target.kind === 'interface_wrapper'
                );
                setStep('basic');
                form.setFieldsValue({
                  tool_id: record.tool_id,
                  name: record.name,
                  short_description: record.short_description,
                  full_description: record.full_description,
                  max_inline_chars: record.max_inline_chars,
                  response_fields:
                    record.response_fields === null
                      ? undefined
                      : JSON.stringify(record.response_fields),
                  des_id: record.des_id,
                  execution_target_kind: record.execution_target.kind,
                  interface_id:
                    record.execution_target.kind === 'interface_wrapper'
                      ? record.execution_target.interface_id
                      : undefined,
                  upstream_connection_id:
                    record.execution_target.kind === 'mcp_proxy'
                      ? record.execution_target.upstream_connection_id
                      : undefined,
                  remote_tool_name:
                    record.execution_target.kind === 'mcp_proxy'
                      ? record.execution_target.remote_tool_name
                      : undefined,
                  source_schema_hash:
                    record.execution_target.kind === 'mcp_proxy'
                      ? record.execution_target.source_schema_hash
                      : undefined,
                  capability_code:
                    record.execution_target.kind === 'assistant_client'
                      ? record.execution_target.capability_code
                      : undefined,
                  risk_level: record.risk_level,
                  status: record.status
                });
                form.setFieldValue(
                  'parameter_schema',
                  schemaRecord(record.parameter_schema)
                );
                form.setFieldValue(
                  'result_schema',
                  schemaRecord(record.result_schema)
                );
                form.setFieldValue(
                  'input_mapping',
                  record.execution_target.kind === 'mcp_proxy'
                    ? record.input_mapping
                    : record.execution_target.kind === 'interface_wrapper'
                      ? withLegacyCallMappings(record.input_mapping)
                      : normalizeInputMapping(record.input_mapping)
                );
                form.setFieldValue(
                  'output_mapping',
                  record.execution_target.kind === 'mcp_proxy'
                    ? record.output_mapping
                    : schemaRecord(record.output_mapping)
                );
                bumpSchemaEditorRevision();
                setModalOpen(true);
              }}
            />
            <Button
              icon={<ReloadOutlined />}
              size="small"
              disabled={!canManage}
              loading={refreshMutation.isPending}
              onClick={() => refreshMutationRef.current.mutate(record.tool_id)}
            />
            <Popconfirm
              title={i18nText('settings', 'auto.mcp_hard_delete_confirm')}
              disabled={!canManage}
              onConfirm={() =>
                deleteToolMutationRef.current.mutate(record.tool_id)
              }
            >
              <Button
                danger
                icon={<DeleteOutlined />}
                size="small"
                disabled={!canManage}
              />
            </Popconfirm>
          </Space>
        )
      }
    ],
    [
      canManage,
      autoGeneratedToolIdRef,
      bumpSchemaEditorRevision,
      deleteToolMutationRef,
      inputMappingValidRef,
      outputMappingValidRef,
      parameterSchemaValidRef,
      refreshMutationRef,
      resultSchemaValidRef,
      setCallParametersVisible,
      columns,
      form,
      refreshMutation.isPending,
      setEditingTool,
      setModalOpen,
      setStep
    ]
  );
  const configuration = useUserPreferenceDataTableConfiguration<ConsoleMcpTool>(
    {
      preferenceKey: 'settings.mcp-management.tools.v3',
      columns: tableColumns
    }
  );

  return (
    <>
      <DataTableLayout
        filters={
          <DataTableFilterForm
            ariaLabel={i18nText('settingsMcpManagement', 'auto.tool_filters')}
            collapseLabel={i18nText(
              'settingsMcpManagement',
              'auto.collapse_filters'
            )}
            expandLabel={i18nText(
              'settingsMcpManagement',
              'auto.expand_filters'
            )}
            expandedFields={
              <>
                <DataTableFilterField label="risk_level">
                  <Select<McpToolsRouteState['risk_level']>
                    allowClear
                    placeholder="risk_level"
                    value={filterDraft.risk_level}
                    options={['low', 'medium', 'high', 'critical'].map(
                      (value) => ({ label: value, value })
                    )}
                    onChange={(risk_level) =>
                      setFilterDraft((current) => ({
                        ...current,
                        risk_level
                      }))
                    }
                  />
                </DataTableFilterField>
                <DataTableFilterField label="des_id_required">
                  <Select<'true' | 'false'>
                    allowClear
                    placeholder="des_id_required"
                    value={
                      filterDraft.des_id_required === undefined
                        ? undefined
                        : (String(filterDraft.des_id_required) as
                            | 'true'
                            | 'false')
                    }
                    options={[
                      { label: 'true', value: 'true' },
                      { label: 'false', value: 'false' }
                    ]}
                    onChange={(value) =>
                      setFilterDraft((current) => ({
                        ...current,
                        des_id_required:
                          value === undefined ? undefined : value === 'true'
                      }))
                    }
                  />
                </DataTableFilterField>
                <DataTableFilterField label="status">
                  <Select<McpToolsRouteState['status']>
                    allowClear
                    placeholder="status"
                    value={filterDraft.status}
                    options={['draft', 'enabled', 'disabled', 'archived'].map(
                      (value) => ({ label: value, value })
                    )}
                    onChange={(status) =>
                      setFilterDraft((current) => ({ ...current, status }))
                    }
                  />
                </DataTableFilterField>
              </>
            }
            resetLabel={i18nText('settings', 'auto.reset')}
            submitLabel={i18nText(
              'settingsMcpManagement',
              'auto.apply_filters'
            )}
            onReset={resetFilters}
            onSubmit={applyFilters}
          >
            <DataTableFilterField
              label={i18nText('settingsMcpManagement', 'auto.tool_keyword')}
            >
              <Input
                allowClear
                placeholder={i18nText(
                  'settingsMcpManagement',
                  'auto.tool_keyword_placeholder'
                )}
                type="search"
                value={filterDraft.keyword ?? ''}
                onChange={(event) =>
                  setFilterDraft((current) => ({
                    ...current,
                    keyword: event.target.value
                  }))
                }
              />
            </DataTableFilterField>
            <DataTableFilterField
              label={i18nText('settingsMcpManagement', 'auto.tool_type')}
            >
              <Select<McpToolsRouteState['execution_target_kind']>
                allowClear
                aria-label={i18nText('settingsMcpManagement', 'auto.tool_type')}
                placeholder={i18nText(
                  'settingsMcpManagement',
                  'auto.tool_type'
                )}
                value={filterDraft.execution_target_kind}
                options={[
                  {
                    label: i18nText(
                      'settingsMcpManagement',
                      'auto.tool_type_interface_wrapper'
                    ),
                    value: 'interface_wrapper'
                  },
                  {
                    label: i18nText(
                      'settingsMcpManagement',
                      'auto.tool_type_mcp_proxy'
                    ),
                    value: 'mcp_proxy'
                  }
                ]}
                onChange={(execution_target_kind) =>
                  setFilterDraft((current) => ({
                    ...current,
                    execution_target_kind
                  }))
                }
              />
            </DataTableFilterField>
            <DataTableFilterField label="operation">
              <Select<string>
                allowClear
                showSearch
                optionFilterProp="label"
                placeholder="operation"
                value={filterDraft.interface_id}
                options={interfaceCapabilities.map((entry) => ({
                  label: `${interfaceOptionLabel(entry)} ${entry.interface_id}`,
                  value: entry.interface_id
                }))}
                onChange={(interface_id) =>
                  setFilterDraft((current) => ({
                    ...current,
                    interface_id
                  }))
                }
              />
            </DataTableFilterField>
          </DataTableFilterForm>
        }
      >
        <DataTable
          columns={tableColumns}
          configuration={configuration}
          dataSource={visibleTools}
          page={routeState.page}
          pageSize={MCP_TOOLS_PAGE_SIZE}
          total={filteredTools.length}
          rowKey="id"
          toolbar={
            <Flex justify="flex-end" gap={8} wrap>
              <Button
                type="primary"
                icon={<PlusOutlined />}
                disabled={!canManage}
                onClick={() => {
                  autoGeneratedToolIdRef.current = '';
                  inputMappingValidRef.current = true;
                  outputMappingValidRef.current = true;
                  parameterSchemaValidRef.current = true;
                  resultSchemaValidRef.current = true;
                  setEditingTool(null);
                  setCallParametersVisible(false);
                  setStep('basic');
                  form.setFieldsValue({
                    tool_id: '',
                    name: '',
                    short_description: '',
                    full_description: '',
                    max_inline_chars: undefined,
                    response_fields: undefined,
                    des_id: buildRandomToolIdSeed(),
                    execution_target_kind: 'interface_wrapper',
                    interface_id: undefined,
                    risk_level: 'high',
                    status: 'draft'
                  });
                  form.setFieldValue('parameter_schema', emptyObjectSchema());
                  form.setFieldValue('result_schema', emptyObjectSchema());
                  form.setFieldValue('input_mapping', {
                    interface_parameters: MCP_CALL_PARAMETERS,
                    mappings: []
                  });
                  form.setFieldValue('output_mapping', emptyObjectSchema());
                  bumpSchemaEditorRevision();
                  setModalOpen(true);
                }}
              >
                {i18nText('settings', 'auto.new')}
              </Button>
              <Button
                icon={<UploadOutlined />}
                onClick={handleExportCatalog}
                loading={exportingCatalog}
              >
                {i18nText('settings', 'auto.export')}
              </Button>
              <Button
                onClick={() =>
                  queryClient.invalidateQueries({
                    queryKey: settingsMcpCatalogQueryKey
                  })
                }
              >
                {i18nText('settings', 'auto.refresh')}
              </Button>
              <DataTableColumnSettings
                columns={tableColumns}
                configuration={configuration}
              />
            </Flex>
          }
          onPageChange={(page) => updateRouteState({ ...routeState, page })}
        />
      </DataTableLayout>
      <FixedHeightModal
        width="70vw"
        resizable
        className="mcp-management__tool-modal"
        open={modalOpen}
        title={
          editingTool
            ? i18nText('settings', 'auto.edit')
            : i18nText('settings', 'auto.new')
        }
        onCancel={() => setModalOpen(false)}
        onOk={() => form.submit()}
        confirmLoading={saveToolMutation.isPending}
        footer={
          <Space wrap>
            {previousToolStep ? (
              <Button
                icon={<LeftOutlined />}
                disabled={saveToolMutation.isPending}
                onClick={() => setStep(previousToolStep.value)}
              >
                上一步
              </Button>
            ) : null}
            {nextToolStep ? (
              <Button
                icon={<RightOutlined />}
                disabled={saveToolMutation.isPending}
                onClick={() => setStep(nextToolStep.value)}
              >
                下一步
              </Button>
            ) : null}
            <Button
              aria-label={i18nText('settings', 'auto.cancel')}
              onClick={() => setModalOpen(false)}
            >
              Cancel
            </Button>
            <Button
              aria-label={i18nText('settings', 'auto.save')}
              type="primary"
              loading={saveToolMutation.isPending}
              onClick={() => form.submit()}
            >
              {i18nText('settings', 'auto.save')}
            </Button>
          </Space>
        }
        bodyHeader={
          <>
            <Steps
              size="small"
              current={toolStepIndex}
              items={TOOL_FORM_STEPS.map((entry) => ({
                title: entry.title
              }))}
            />
            <Segmented
              block
              className="mcp-management__segmented"
              value={step}
              options={TOOL_FORM_STEPS.map((entry) => ({
                label: entry.label,
                value: entry.value
              }))}
              onChange={(value) => setStep(String(value))}
            />
          </>
        }
      >
        <Form
          form={form}
          className="mcp-management__tool-form"
          layout="vertical"
          onFinish={(values) => saveToolMutation.mutate(values)}
          onValuesChange={(changedValues, values) => {
            if (editingTool || !('name' in changedValues)) {
              return;
            }

            const currentToolId = values.tool_id ?? '';
            if (
              currentToolId &&
              currentToolId !== autoGeneratedToolIdRef.current
            ) {
              return;
            }

            const generatedToolId = buildReadableToolId(values.name ?? '');
            autoGeneratedToolIdRef.current = generatedToolId;
            form.setFieldValue('tool_id', generatedToolId);
          }}
        >
          <div hidden={step !== 'basic'}>
            <Form.Item name="name" label="name" rules={[{ required: true }]}>
              <Input />
            </Form.Item>
            <Form.Item htmlFor="tool_id" label="tool_id" required>
              {editingTool ? (
                <Form.Item
                  name="tool_id"
                  noStyle
                  rules={[{ required: true, whitespace: true }]}
                >
                  <Input disabled id="tool_id" />
                </Form.Item>
              ) : (
                <Space.Compact block>
                  <Form.Item
                    name="tool_id"
                    noStyle
                    rules={[{ required: true, whitespace: true }]}
                  >
                    <Input id="tool_id" />
                  </Form.Item>
                  <Tooltip title="随机生成 tool_id">
                    <Button
                      htmlType="button"
                      icon={<ReloadOutlined />}
                      onClick={() => {
                        autoGeneratedToolIdRef.current = '';
                        form.setFieldValue(
                          'tool_id',
                          buildReadableToolId('', buildRandomToolIdSeed())
                        );
                      }}
                    />
                  </Tooltip>
                </Space.Compact>
              )}
            </Form.Item>
            <Form.Item htmlFor="des_id" label="des_id" required>
              <Space.Compact block>
                <Form.Item
                  name="des_id"
                  noStyle
                  rules={[{ required: true, whitespace: true }]}
                >
                  <Input id="des_id" />
                </Form.Item>
                <Tooltip title="随机生成 des_id">
                  <Button
                    htmlType="button"
                    icon={<ReloadOutlined />}
                    onClick={() => {
                      form.setFieldValue('des_id', buildRandomToolIdSeed());
                    }}
                  />
                </Tooltip>
              </Space.Compact>
            </Form.Item>
            <McpToolReturnDefaultsFields />
            <Form.Item
              name="status"
              label="status"
              rules={[{ required: true }]}
            >
              <Select
                options={['draft', 'enabled', 'disabled', 'archived'].map(
                  (value) => ({ label: value, value })
                )}
              />
            </Form.Item>
            <Form.Item
              name="short_description"
              label="short_description"
              rules={[{ required: true }]}
            >
              <Input />
            </Form.Item>
            <Form.Item name="full_description" label="full_description">
              <MarkdownIrEditor ariaLabel="full_description" />
            </Form.Item>
          </div>
          <div hidden={step !== 'interface'}>
            {editingTool?.execution_target.kind === 'assistant_client' ? (
              <Space
                orientation="vertical"
                size="middle"
                className="mcp-management__stack"
              >
                <Descriptions bordered size="small" column={1}>
                  <Descriptions.Item label="capability_code">
                    {editingTool.execution_target.capability_code}
                  </Descriptions.Item>
                </Descriptions>
                <Form.Item
                  name="risk_level"
                  label="risk_level"
                  rules={[{ required: true }]}
                >
                  <Select
                    options={['low', 'medium', 'high', 'critical'].map(
                      (value) => ({ label: value, value })
                    )}
                  />
                </Form.Item>
              </Space>
            ) : editingTool?.execution_target.kind === 'mcp_proxy' ? (
              <Space
                orientation="vertical"
                size="middle"
                className="mcp-management__stack"
              >
                <Descriptions bordered size="small" column={1}>
                  <Descriptions.Item
                    label={i18nText(
                      'settingsMcpManagement',
                      'auto.upstream_connection_id'
                    )}
                  >
                    {editingTool.execution_target.upstream_connection_id}
                  </Descriptions.Item>
                  <Descriptions.Item
                    label={i18nText(
                      'settingsMcpManagement',
                      'auto.upstream_remote_tool_name'
                    )}
                  >
                    {editingTool.execution_target.remote_tool_name}
                  </Descriptions.Item>
                  <Descriptions.Item label="source_schema_hash">
                    {editingTool.execution_target.source_schema_hash}
                  </Descriptions.Item>
                </Descriptions>
                <Form.Item
                  name="risk_level"
                  label="risk_level"
                  rules={[{ required: true }]}
                >
                  <Select
                    options={['low', 'medium', 'high', 'critical'].map(
                      (value) => ({ label: value, value })
                    )}
                  />
                </Form.Item>
              </Space>
            ) : (
              <>
                <Form.Item
                  name="interface_id"
                  label="operation"
                  rules={[{ required: true }]}
                >
                  <Select
                    showSearch
                    optionFilterProp="label"
                    options={interfaceCapabilities.map((entry) => ({
                      label: `${interfaceOptionLabel(entry)} - ${entry.interface_id}${
                        entry.bindable ? '' : ` (${entry.disabled_reason})`
                      }`,
                      value: entry.interface_id,
                      disabled: !entry.bindable
                    }))}
                  />
                </Form.Item>
                <Form.Item
                  noStyle
                  shouldUpdate={(previous, current) =>
                    previous.interface_id !== current.interface_id
                  }
                >
                  {({ getFieldValue }) => {
                    const selectedInterface = interfaceCapabilities.find(
                      (entry) =>
                        entry.interface_id === getFieldValue('interface_id')
                    );

                    if (!selectedInterface) {
                      return null;
                    }

                    return (
                      <Descriptions bordered size="small" column={1}>
                        <Descriptions.Item label="operation">
                          {interfaceOptionLabel(selectedInterface)}
                        </Descriptions.Item>
                        <Descriptions.Item label="operationId">
                          {selectedInterface.interface_id}
                        </Descriptions.Item>
                        <Descriptions.Item label="risk_level">
                          {selectedInterface.risk_level}
                        </Descriptions.Item>
                        <Descriptions.Item label="permission_code">
                          {selectedInterface.permission_code ?? '-'}
                        </Descriptions.Item>
                      </Descriptions>
                    );
                  }}
                </Form.Item>
              </>
            )}
          </div>
          {step === 'input' ? (
            <div>
              {editingTool?.execution_target.kind === 'mcp_proxy' ? (
                <Space
                  orientation="vertical"
                  size="middle"
                  className="mcp-management__stack"
                >
                  <Typography.Text strong>parameter_schema</Typography.Text>
                  <Form.Item
                    noStyle
                    shouldUpdate={(previous, current) =>
                      previous.parameter_schema !== current.parameter_schema
                    }
                  >
                    {({ getFieldValue }) => (
                      <JsonSchemaInlineEditor
                        fallbackRootType="object"
                        resetKey={`parameter:${schemaEditorRevision}`}
                        schema={schemaRecord(getFieldValue('parameter_schema'))}
                        structureMode="fields"
                        onChange={setParameterSchemaValue}
                        onValidityChange={setParameterSchemaValidity}
                      />
                    )}
                  </Form.Item>
                  <Typography.Text strong>input_mapping</Typography.Text>
                  <Form.Item
                    noStyle
                    shouldUpdate={(previous, current) =>
                      previous.input_mapping !== current.input_mapping
                    }
                  >
                    {({ getFieldValue }) => (
                      <McpProxyMappingEditor
                        direction="input"
                        value={
                          getFieldValue(
                            'input_mapping'
                          ) as ConsoleMcpProxyInputMapping
                        }
                        onChange={setInputMappingValue}
                        onValidityChange={setInputMappingValidity}
                      />
                    )}
                  </Form.Item>
                </Space>
              ) : (
                <>
                  <Form.Item
                    noStyle
                    shouldUpdate={(previous, current) =>
                      previous.interface_id !== current.interface_id ||
                      previous.input_mapping !== current.input_mapping
                    }
                  >
                    {({ getFieldValue }) => {
                      const selectedInterface = interfaceCapabilities.find(
                        (entry) =>
                          entry.interface_id === getFieldValue('interface_id')
                      );

                      return (
                        <Flex justify="space-between" align="center" gap={12}>
                          <SelectedInterfaceOperationTitle
                            selectedInterface={selectedInterface}
                          />
                          <Button
                            disabled={!selectedInterface}
                            onClick={() =>
                              applyInterfaceToMapping(
                                'input_mapping',
                                selectedInterface
                              )
                            }
                          >
                            {i18nText(
                              'settings',
                              'auto.mcp_get_interface_parameters'
                            )}
                          </Button>
                        </Flex>
                      );
                    }}
                  </Form.Item>
                  <Form.Item
                    noStyle
                    shouldUpdate={(previous, current) =>
                      previous.input_mapping !== current.input_mapping
                    }
                  >
                    {({ getFieldValue }) => (
                      <div className="mcp-management__input-mapping-editor">
                        <McpInputMappingEditor
                          resetKey={`input:${schemaEditorRevision}`}
                          showCallParameters={callParametersVisible}
                          value={getFieldValue('input_mapping')}
                          onChange={setInputMappingValue}
                          onValidityChange={setInputMappingValidity}
                        />
                      </div>
                    )}
                  </Form.Item>
                </>
              )}
            </div>
          ) : null}
          {step === 'output' ? (
            <div>
              {editingTool?.execution_target.kind === 'mcp_proxy' ? (
                <Space
                  orientation="vertical"
                  size="middle"
                  className="mcp-management__stack"
                >
                  <Typography.Text strong>result_schema</Typography.Text>
                  <Form.Item
                    noStyle
                    shouldUpdate={(previous, current) =>
                      previous.result_schema !== current.result_schema
                    }
                  >
                    {({ getFieldValue }) => (
                      <JsonSchemaInlineEditor
                        fallbackRootType="object"
                        resetKey={`result:${schemaEditorRevision}`}
                        schema={schemaRecord(getFieldValue('result_schema'))}
                        structureMode="fields"
                        onChange={setResultSchemaValue}
                        onValidityChange={setResultSchemaValidity}
                      />
                    )}
                  </Form.Item>
                  <Typography.Text strong>output_mapping</Typography.Text>
                  <Form.Item
                    noStyle
                    shouldUpdate={(previous, current) =>
                      previous.output_mapping !== current.output_mapping
                    }
                  >
                    {({ getFieldValue }) => (
                      <McpProxyMappingEditor
                        direction="output"
                        value={
                          getFieldValue(
                            'output_mapping'
                          ) as ConsoleMcpProxyOutputMapping
                        }
                        onChange={setOutputMappingValue}
                        onValidityChange={setOutputMappingValidity}
                      />
                    )}
                  </Form.Item>
                </Space>
              ) : (
                <>
                  <Form.Item
                    noStyle
                    shouldUpdate={(previous, current) =>
                      previous.interface_id !== current.interface_id ||
                      previous.output_mapping !== current.output_mapping
                    }
                  >
                    {({ getFieldValue }) => {
                      const selectedInterface = interfaceCapabilities.find(
                        (entry) =>
                          entry.interface_id === getFieldValue('interface_id')
                      );

                      return (
                        <Flex justify="space-between" align="center" gap={12}>
                          <SelectedInterfaceOperationTitle
                            selectedInterface={selectedInterface}
                          />
                          <Button
                            disabled={!selectedInterface}
                            onClick={() =>
                              applyInterfaceToMapping(
                                'output_mapping',
                                selectedInterface
                              )
                            }
                          >
                            {i18nText(
                              'settings',
                              'auto.mcp_get_interface_result'
                            )}
                          </Button>
                        </Flex>
                      );
                    }}
                  </Form.Item>
                  <Form.Item
                    noStyle
                    shouldUpdate={(previous, current) =>
                      previous.output_mapping !== current.output_mapping
                    }
                  >
                    {({ getFieldValue }) => (
                      <div className="mcp-management__schema-editor">
                        <JsonSchemaInlineEditor
                          fallbackRootType="object"
                          resetKey={`output:${schemaEditorRevision}`}
                          schema={schemaRecord(getFieldValue('output_mapping'))}
                          structureMode="fields"
                          onChange={setOutputMappingValue}
                          onValidityChange={setOutputMappingValidity}
                        />
                      </div>
                    )}
                  </Form.Item>
                </>
              )}
            </div>
          ) : null}
          {step === 'debug' ? (
            editingTool?.execution_target.kind === 'mcp_proxy' ? (
              <Form.Item
                noStyle
                shouldUpdate={(previous, current) =>
                  previous.input_mapping !== current.input_mapping
                }
              >
                {({ getFieldValue }) => (
                  <McpProxyToolDebugPanel
                    toolId={editingTool.tool_id}
                    csrfToken={csrfToken}
                    inputMapping={
                      getFieldValue(
                        'input_mapping'
                      ) as ConsoleMcpProxyInputMapping
                    }
                    executeDebug={executeSettingsMcpProxyToolDebug}
                  />
                )}
              </Form.Item>
            ) : (
              <Form.Item
                noStyle
                shouldUpdate={(previous, current) =>
                  previous.interface_id !== current.interface_id ||
                  previous.input_mapping !== current.input_mapping ||
                  previous.output_mapping !== current.output_mapping
                }
              >
                {({ getFieldValue }) => {
                  const selectedInterface = interfaceCapabilities.find(
                    (entry) =>
                      entry.interface_id === getFieldValue('interface_id')
                  );

                  return (
                    <div>
                      <McpToolDebugPanel
                        csrfToken={csrfToken}
                        executeDebug={executeSettingsMcpToolDebug}
                        interfaceId={getFieldValue('interface_id')}
                        inputMapping={getFieldValue('input_mapping')}
                        operationLabel={
                          selectedInterface
                            ? interfaceOptionLabel(selectedInterface)
                            : null
                        }
                        outputMapping={schemaRecord(
                          getFieldValue('output_mapping')
                        )}
                      />
                    </div>
                  );
                }}
              </Form.Item>
            )
          ) : null}
        </Form>
      </FixedHeightModal>
    </>
  );
}
