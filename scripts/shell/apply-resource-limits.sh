#!/usr/bin/env bash
set -euo pipefail

script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
config_file=${1:-"$script_dir/resource-limits.conf"}

if [[ ! -r $config_file ]]; then
  printf 'Resource-limit config is not readable: %s\n' "$config_file" >&2
  exit 2
fi

# The profile is a trusted local shell config. Paths are resolved after loading
# it so profile values cannot redirect writes outside the intended locations.
# shellcheck source=/dev/null
source "$config_file"

profile_mode=${PROFILE_MODE:-}
if [[ $profile_mode != limited && $profile_mode != unlimited ]]; then
  printf 'PROFILE_MODE must be limited or unlimited\n' >&2
  exit 2
fi

user_home=$(getent passwd "$(id -u)" | cut -d: -f6)
systemd_user_dir=${RESOURCE_LIMITS_SYSTEMD_USER_DIR:-"$user_home/.config/systemd/user"}
user_bin_dir=${RESOURCE_LIMITS_USER_BIN_DIR:-"$user_home/.local/bin"}
repo_root=${RESOURCE_LIMITS_REPO_ROOT:-$(cd -- "$script_dir/../.." && pwd)}
systemctl_bin=${RESOURCE_LIMITS_SYSTEMCTL_BIN:-systemctl}
real_cargo=${RESOURCE_LIMITS_REAL_CARGO:-"$user_home/.cargo/bin/cargo"}

session_config="$systemd_user_dir/session.slice.d/50-memory-protection.conf"
app_config="$systemd_user_dir/app.slice.d/50-memory-budget.conf"
dev_config="$systemd_user_dir/dev.slice"
rust_config="$systemd_user_dir/rust-build.slice"
cargo_wrapper="$user_bin_dir/cargo"
project_config="$repo_root/.1flowbase.verify.local.json"

require_value() {
  local name=$1
  if [[ -z ${!name:-} ]]; then
    printf '%s is required for PROFILE_MODE=limited\n' "$name" >&2
    exit 2
  fi
}

write_limited_profile() {
  local required
  for required in \
    SESSION_MEMORY_LOW \
    APP_OOM_PRESSURE_LIMIT \
    APP_OOM_PRESSURE_DURATION \
    DEV_OOM_PRESSURE_LIMIT \
    DEV_OOM_PRESSURE_DURATION \
    RUST_MEMORY_HIGH \
    RUST_MEMORY_MAX \
    RUST_MEMORY_SWAP_MAX \
    CARGO_MAX_JOBS \
    PROJECT_CARGO_JOBS \
    PROJECT_CARGO_TEST_THREADS \
    PROJECT_CARGO_INCREMENTAL; do
    require_value "$required"
  done

  if [[ ! $CARGO_MAX_JOBS =~ ^[1-9][0-9]*$ ||
        ! $PROJECT_CARGO_JOBS =~ ^[1-9][0-9]*$ ||
        ! $PROJECT_CARGO_TEST_THREADS =~ ^[1-9][0-9]*$ ||
        ! $PROJECT_CARGO_INCREMENTAL =~ ^(true|false)$ ]]; then
    printf 'Cargo job counts must be positive integers and incremental must be true or false\n' >&2
    exit 2
  fi

  mkdir -p -- "$(dirname -- "$session_config")" "$(dirname -- "$app_config")" \
    "$systemd_user_dir" "$user_bin_dir"

  cat >"$session_config" <<EOF
[Slice]
MemoryAccounting=yes
MemoryLow=$SESSION_MEMORY_LOW
ManagedOOMPreference=avoid
EOF

  cat >"$app_config" <<EOF
[Slice]
MemoryAccounting=yes
ManagedOOMMemoryPressure=kill
ManagedOOMMemoryPressureLimit=$APP_OOM_PRESSURE_LIMIT
ManagedOOMMemoryPressureDurationSec=$APP_OOM_PRESSURE_DURATION
EOF

  cat >"$dev_config" <<EOF
[Unit]
Description=Resource-controlled development workloads

[Slice]
MemoryAccounting=yes
ManagedOOMMemoryPressure=kill
ManagedOOMMemoryPressureLimit=$DEV_OOM_PRESSURE_LIMIT
ManagedOOMMemoryPressureDurationSec=$DEV_OOM_PRESSURE_DURATION
EOF

  cat >"$rust_config" <<EOF
[Unit]
Description=Memory budget for Rust builds

[Slice]
MemoryAccounting=yes
MemoryHigh=$RUST_MEMORY_HIGH
MemoryMax=$RUST_MEMORY_MAX
MemorySwapMax=$RUST_MEMORY_SWAP_MAX
ManagedOOMPreference=avoid
EOF

  cat >"$cargo_wrapper" <<EOF
#!/usr/bin/env bash
set -euo pipefail

# Generated by scripts/shell/apply-resource-limits.sh.
readonly real_cargo='$real_cargo'
readonly memory_budget_cargo_jobs=$CARGO_MAX_JOBS

if [[ ! \${CARGO_BUILD_JOBS:-} =~ ^[1-9][0-9]*$ ]] ||
    (( CARGO_BUILD_JOBS > memory_budget_cargo_jobs )); then
  export CARGO_BUILD_JOBS=\$memory_budget_cargo_jobs
fi

capped_cargo_args=()
while (( \$# > 0 )); do
  case \$1 in
    --jobs|-j)
      capped_cargo_args+=("\$1")
      shift
      if (( \$# > 0 )) && [[ \$1 =~ ^[1-9][0-9]*$ ]] &&
          (( \$1 > memory_budget_cargo_jobs )); then
        capped_cargo_args+=("\$memory_budget_cargo_jobs")
      elif (( \$# > 0 )); then
        capped_cargo_args+=("\$1")
      fi
      ;;
    --jobs=[1-9]*|-j[1-9]*)
      job_value=\${1#*=}
      [[ \$1 == -j* ]] && job_value=\${1#-j}
      if [[ \$job_value =~ ^[1-9][0-9]*$ ]] &&
          (( job_value > memory_budget_cargo_jobs )); then
        [[ \$1 == --jobs=* ]] && capped_cargo_args+=("--jobs=\$memory_budget_cargo_jobs")
        [[ \$1 == -j* ]] && capped_cargo_args+=("-j\$memory_budget_cargo_jobs")
      else
        capped_cargo_args+=("\$1")
      fi
      ;;
    *) capped_cargo_args+=("\$1") ;;
  esac
  shift
done
set -- "\${capped_cargo_args[@]}"

if [[ \${CARGO_MEMORY_BUDGET_ACTIVE:-} == 1 ]]; then
  exec "\$real_cargo" "\$@"
fi

if ! systemctl --user is-active default.target >/dev/null 2>&1; then
  exec "\$real_cargo" "\$@"
fi

export CARGO_MEMORY_BUDGET_ACTIVE=1
exec systemd-run --user --scope --quiet --collect \
  --slice=rust-build.slice \
  -- "\$real_cargo" "\$@"
EOF
  chmod 0755 "$cargo_wrapper"

  cat >"$project_config" <<EOF
{
  "backend": {
    "cargoJobs": $PROJECT_CARGO_JOBS,
    "cargoTestThreads": $PROJECT_CARGO_TEST_THREADS,
    "incremental": $PROJECT_CARGO_INCREMENTAL
  }
}
EOF

  "$systemctl_bin" --user daemon-reload
  "$systemctl_bin" --user set-property --runtime rust-build.slice \
    "MemoryHigh=$RUST_MEMORY_HIGH" \
    "MemoryMax=$RUST_MEMORY_MAX" \
    "MemorySwapMax=$RUST_MEMORY_SWAP_MAX"
}

write_unlimited_profile() {
  rm -f -- "$session_config" "$app_config" "$dev_config" "$rust_config" \
    "$cargo_wrapper" "$project_config"
  rmdir --ignore-fail-on-non-empty -- "$(dirname -- "$session_config")" \
    "$(dirname -- "$app_config")" 2>/dev/null || true

  "$systemctl_bin" --user daemon-reload
  if "$systemctl_bin" --user is-active --quiet rust-build.slice; then
    "$systemctl_bin" --user set-property --runtime rust-build.slice \
      MemoryHigh=infinity MemoryMax=infinity MemorySwapMax=infinity
  fi
}

if [[ $profile_mode == limited ]]; then
  write_limited_profile
else
  write_unlimited_profile
fi

printf 'Applied resource profile %s from %s\n' "$profile_mode" "$config_file"
