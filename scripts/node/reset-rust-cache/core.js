const { spawn } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const {
  runBuildCacheCleanup,
} = require('../clean-build-cache/core.js');
const { buildCargoCommandEnv } = require('../testing/warning-capture.js');
const {
  getAvailableParallelism,
  getLocalCpuBudget,
  isCiEnvironment,
  loadVerifyRuntimeConfig,
} = require('../testing/verify-runtime.js');

function getRepoRoot() {
  return path.resolve(__dirname, '..', '..', '..');
}

function buildCargoEnv({ cargoJobs, cpuBudget, incremental, testProfile = false }) {
  const env = {
    ...buildCargoCommandEnv({ cargoParallelism: cargoJobs, incremental, testProfile }),
    ONEFLOWBASE_CARGO_JOB_LIMIT: String(cpuBudget),
  };

  if (testProfile) {
    env.CARGO_PROFILE_TEST_DEBUG = '0';
  }

  return env;
}

function readExplicitCpuCap(env) {
  const value = env.ONEFLOWBASE_CARGO_JOB_LIMIT;
  if (value === undefined || value === '' || value === 'auto') return Infinity;
  if (typeof value !== 'string' || !/^[1-9][0-9]*$/.test(value)) {
    throw new Error('ONEFLOWBASE_CARGO_JOB_LIMIT must be a positive integer or auto');
  }
  return Number(value);
}

function readExplicitBuildJobs(env) {
  const value = env.CARGO_BUILD_JOBS;
  // Match the installed wrapper: unsupported job syntax falls back to its budget.
  return typeof value === 'string' && /^[1-9][0-9]*$/.test(value) ? Number(value) : Infinity;
}

function buildRustWarmupPlan({
  incremental,
  availableParallelism = getAvailableParallelism(),
  cargoJobs,
  env = process.env,
}) {
  const localCpuBudget = getLocalCpuBudget(availableParallelism);
  const ci = isCiEnvironment(env);
  const cpuBudget = Math.min(
    ci ? availableParallelism : localCpuBudget,
    readExplicitCpuCap(env),
  );
  const configuredJobs = cargoJobs ?? (ci ? availableParallelism : localCpuBudget);
  if (!Number.isSafeInteger(configuredJobs) || configuredJobs < 1 || configuredJobs > availableParallelism) {
    throw new Error('backend.cargoJobs must be a positive safe integer not exceeding availableParallelism');
  }
  const ordinaryJobs = Math.min(configuredJobs, readExplicitBuildJobs(env), cpuBudget);
  const devEnv = buildCargoEnv({ cargoJobs: ordinaryJobs, cpuBudget, incremental });
  // Serial compiler jobs reduce overlapping large test targets while preserving
  // the independent cgroup CPU upper bound; it does not guarantee parallel CPU use.
  const testEnv = buildCargoEnv({ cargoJobs: ci ? ordinaryJobs : 1, cpuBudget, incremental, testProfile: true });

  return [
    {
      label: 'locked dependencies',
      args: ['fetch', '--manifest-path', 'api/Cargo.toml', '--target', 'host-tuple', '--locked'],
      env: devEnv,
    },
    {
      label: 'api-server dev-up target',
      args: [
        'build',
        '--manifest-path',
        'api/Cargo.toml',
        '-p',
        'api-server',
        '--bin',
        'api-server',
        '--features',
        'tikv-jemallocator/stats',
        '--locked',
        '--timings',
      ],
      env: devEnv,
    },
    {
      label: 'workspace test-profile libraries and binary tests',
      // Test mode preserves workspace dev-dependency feature unification. A
      // separate `build --profile test --lib` can produce incompatible caches.
      // Binary tests need the ordinary library, without its large lib-test target.
      args: [
        'test',
        '--manifest-path',
        'api/Cargo.toml',
        '--workspace',
        '--bins',
        '--no-run',
        '--locked',
        '--timings',
      ],
      env: testEnv,
    },
    {
      label: 'workspace test targets',
      args: [
        'test',
        '--manifest-path',
        'api/Cargo.toml',
        '--workspace',
        '--all-targets',
        '--no-run',
        '--locked',
        '--timings',
      ],
      env: testEnv,
    },
  ];
}

async function cleanupBackendCache({ repoRoot, writeStdout }) {
  return runBuildCacheCleanup({
    repoRoot,
    options: {
      dryRun: false,
      help: false,
      scope: 'backend',
    },
    writeStdout,
  });
}

function resolveWarmupCargo({ platform = process.platform, homeDir = os.homedir() } = {}) {
  if (platform !== 'linux') return 'cargo';
  const wrapper = path.join(homeDir, '.local', 'bin', 'cargo');
  if (!fs.existsSync(wrapper)) return 'cargo';
  const descriptor = fs.openSync(wrapper, 'r');
  try {
    const header = Buffer.alloc(256);
    const length = fs.readSync(descriptor, header, 0, header.length, 0);
    // Recognize only our installed resource wrapper; preserve other Cargo setups.
    return header.toString('utf8', 0, length).includes('# Generated by scripts/shell/apply-resource-limits.sh.')
      ? wrapper
      : 'cargo';
  } finally {
    fs.closeSync(descriptor);
  }
}

function runCargo({ repoRoot, args, env }) {
  return new Promise((resolve, reject) => {
    const child = spawn(resolveWarmupCargo(), args, {
      cwd: repoRoot,
      env: { ...process.env, ...env },
      stdio: 'inherit',
    });

    child.once('error', reject);
    child.once('exit', (code, signal) => {
      if (signal) {
        reject(new Error(`cargo 被信号 ${signal} 终止`));
        return;
      }
      resolve(code ?? 1);
    });
  });
}

async function runRustCacheReset({
  repoRoot = getRepoRoot(),
  warmupOnly = false,
  env = process.env,
  availableParallelism = getAvailableParallelism(),
  loadRuntimeConfigImpl = loadVerifyRuntimeConfig,
  cleanupBackendCacheImpl = cleanupBackendCache,
  runCargoImpl = runCargo,
  writeStdout = (text) => process.stdout.write(text),
} = {}) {
  const runtimeConfig = loadRuntimeConfigImpl({ repoRoot, env, availableParallelism });
  const { incremental, cargoJobs } = runtimeConfig.backend;
  const plan = buildRustWarmupPlan({ incremental, cargoJobs, availableParallelism, env });

  if (warmupOnly) {
    writeStdout('[1flowbase-reset-rust-cache] 保留已有缓存与运行中的服务，仅预热 Rust 构建和测试目标。\n');
  } else {
    writeStdout('[1flowbase-reset-rust-cache] 清理 api/target 并停止 api-server。\n');
    const cleanupStatus = await cleanupBackendCacheImpl({ repoRoot, writeStdout });
    if (cleanupStatus !== undefined && cleanupStatus !== 0) {
      return cleanupStatus;
    }
  }

  for (const stage of plan) {
    const startedAt = Date.now();
    writeStdout(
      `[1flowbase-reset-rust-cache] 预热 ${stage.label} `
      + `(jobs=${stage.env.CARGO_BUILD_JOBS}, cpu-cap=${stage.env.ONEFLOWBASE_CARGO_JOB_LIMIT}, incremental=${stage.env.CARGO_INCREMENTAL ?? 'profile'})。\n`,
    );
    const status = await runCargoImpl({ repoRoot, ...stage });
    if (status !== 0) {
      writeStdout(
        `[1flowbase-reset-rust-cache] ${stage.label} 失败（exit=${status}），停止后续预热。\n`,
      );
      return status;
    }
    writeStdout(
      `[1flowbase-reset-rust-cache] ${stage.label} 完成（耗时 ${((Date.now() - startedAt) / 1000).toFixed(1)}s）。\n`,
    );
  }

  writeStdout(`[1flowbase-reset-rust-cache] Rust ${warmupOnly ? '全量预热' : '缓存清理与全量预热'}完成。\n`);
  return 0;
}

module.exports = {
  buildRustWarmupPlan,
  cleanupBackendCache,
  getRepoRoot,
  resolveWarmupCargo,
  runCargo,
  runRustCacheReset,
};
