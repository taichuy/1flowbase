test('warmup selects the installed project resource wrapper without replacing unrelated Cargo setups', () => {
  const homeDir = fs.mkdtempSync(path.join(os.tmpdir(), 'rust-warmup-cargo-'));
  const wrapper = path.join(homeDir, '.local', 'bin', 'cargo');
  try {
    assert.equal(resolveWarmupCargo({ platform: 'linux', homeDir }), 'cargo');
    fs.mkdirSync(path.dirname(wrapper), { recursive: true });
    fs.writeFileSync(wrapper, '#!/bin/sh\n# Some other Cargo installation\n');
    assert.equal(resolveWarmupCargo({ platform: 'linux', homeDir }), 'cargo');
    fs.writeFileSync(wrapper, '#!/usr/bin/env bash\n# Generated by scripts/shell/apply-resource-limits.sh.\n');
    assert.equal(resolveWarmupCargo({ platform: 'linux', homeDir }), wrapper);
    assert.equal(resolveWarmupCargo({ platform: 'darwin', homeDir }), 'cargo');
  } finally {
    fs.rmSync(homeDir, { recursive: true, force: true });
  }
});

